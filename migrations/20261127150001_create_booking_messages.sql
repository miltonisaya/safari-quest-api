-- One conversation per booking between its traveler and the company's staff.
-- from_company tells the two sides apart; read_at is set when the other side
-- opens the thread.
CREATE TABLE booking_messages (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid         UUID        NOT NULL UNIQUE,
    booking_id   BIGINT      NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    sender_id    BIGINT      REFERENCES users(id) ON DELETE SET NULL,
    from_company BOOLEAN     NOT NULL,
    body         TEXT        NOT NULL CHECK (char_length(body) BETWEEN 1 AND 2000),
    read_at      TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_booking_messages_thread ON booking_messages (booking_id, created_at);
CREATE INDEX idx_booking_messages_unread ON booking_messages (booking_id, from_company) WHERE read_at IS NULL;

