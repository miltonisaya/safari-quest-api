-- A traveler's reservation of seats on a sale package. Trip dates come from
-- the package; prices are copied at booking time so later package price
-- changes do not alter existing bookings.
CREATE TABLE bookings
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid             UUID                     NOT NULL UNIQUE,
    code             VARCHAR(20)              NOT NULL UNIQUE, -- booking reference shown to travelers
    package_id       BIGINT                   NOT NULL,
    tour_operator_id BIGINT                   NOT NULL,          -- copied from the package for company scoping
    user_id          BIGINT                   NOT NULL,          -- the traveler
    pax              INTEGER                  NOT NULL,
    unit_price       NUMERIC(12, 2)           NOT NULL,          -- price per person at booking time
    total_price      NUMERIC(12, 2)           NOT NULL,
    status           VARCHAR(20)              NOT NULL DEFAULT 'pending',
    notes            TEXT,
    confirmed_at     TIMESTAMP WITH TIME ZONE,
    cancelled_at     TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at       TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_bookings_package
        FOREIGN KEY (package_id) REFERENCES packages (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_bookings_tour_operator
        FOREIGN KEY (tour_operator_id) REFERENCES tour_operators (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_bookings_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_bookings_pax CHECK (pax >= 1),
    CONSTRAINT chk_bookings_prices CHECK (unit_price >= 0 AND total_price >= 0),
    CONSTRAINT chk_bookings_status CHECK (status IN ('pending', 'confirmed', 'completed', 'cancelled'))
);

CREATE INDEX idx_bookings_package_id ON bookings (package_id);
CREATE INDEX idx_bookings_tour_operator_id ON bookings (tour_operator_id);
CREATE INDEX idx_bookings_user_id ON bookings (user_id);
CREATE INDEX idx_bookings_status ON bookings (status);

