-- Kinds of upload an administrator allows, such as image, document, or video.
CREATE TABLE file_resource_types
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid       UUID                     NOT NULL UNIQUE,
    name       VARCHAR(255)             NOT NULL UNIQUE,
    code       VARCHAR(255)             NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE
);

-- A file a user uploaded. operator_id is the company it belongs to.
CREATE TABLE file_resources
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                  UUID                     NOT NULL UNIQUE,
    name                  VARCHAR(255)             NOT NULL,
    code                  VARCHAR(255)             NOT NULL UNIQUE,
    date_uploaded         TIMESTAMP WITH TIME ZONE NOT NULL,
    file_resource_type_id BIGINT                   NOT NULL,
    operator_id           BIGINT                   NOT NULL,
    path                  VARCHAR(1024)            NOT NULL,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at            TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_file_resources_type
        FOREIGN KEY (file_resource_type_id) REFERENCES file_resource_types (id)
            ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_file_resources_operator
        FOREIGN KEY (operator_id) REFERENCES tour_operators (id)
            ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE INDEX idx_file_resources_type_id ON file_resources (file_resource_type_id);
CREATE INDEX idx_file_resources_operator_id ON file_resources (operator_id);

-- A trip a tour company sells to travellers.
CREATE TABLE packages
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid         UUID                     NOT NULL UNIQUE,
    operator_id  BIGINT                   NOT NULL,
    name         VARCHAR(255)             NOT NULL,
    description  TEXT                     NOT NULL,
    start_date   DATE                     NOT NULL,
    end_date     DATE                     NOT NULL,
    pax          INTEGER                  NOT NULL,
    price        NUMERIC(12, 2)           NOT NULL,
    package_type VARCHAR(100)             NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at   TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_packages_operator
        FOREIGN KEY (operator_id) REFERENCES tour_operators (id)
            ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_packages_dates CHECK (end_date >= start_date),
    CONSTRAINT chk_packages_pax CHECK (pax >= 1),
    CONSTRAINT chk_packages_price CHECK (price >= 0)
);

CREATE INDEX idx_packages_operator_id ON packages (operator_id);
CREATE INDEX idx_packages_package_type ON packages (package_type);

-- Documents, images, and videos attached to a package.
CREATE TABLE package_file_resources
(
    package_id       BIGINT NOT NULL REFERENCES packages (id) ON DELETE CASCADE,
    file_resource_id BIGINT NOT NULL REFERENCES file_resources (id) ON DELETE CASCADE,
    PRIMARY KEY (package_id, file_resource_id)
);

CREATE INDEX idx_package_file_resources_file_resource_id ON package_file_resources (file_resource_id);

