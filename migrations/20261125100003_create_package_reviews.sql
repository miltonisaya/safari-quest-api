-- A traveler's review of a package, tied to their completed booking (one each).
CREATE TABLE package_reviews
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid           UUID                     NOT NULL UNIQUE,
    package_id     BIGINT                   NOT NULL REFERENCES packages (id) ON DELETE CASCADE,
    booking_id     BIGINT                   NOT NULL UNIQUE REFERENCES bookings (id) ON DELETE CASCADE,
    user_id        BIGINT                   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    rating         SMALLINT                 NOT NULL,
    title          VARCHAR(150),
    comment        TEXT,
    operator_reply TEXT,                               -- the company's public answer
    replied_at     TIMESTAMP WITH TIME ZONE,
    is_hidden      BOOLEAN                  NOT NULL DEFAULT FALSE, -- hidden by an administrator
    hidden_at      TIMESTAMP WITH TIME ZONE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT chk_package_reviews_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE INDEX idx_package_reviews_package_id ON package_reviews (package_id);
CREATE INDEX idx_package_reviews_user_id ON package_reviews (user_id);

