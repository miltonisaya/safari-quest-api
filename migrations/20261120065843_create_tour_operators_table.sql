CREATE TABLE tour_operators
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                UUID                     NOT NULL UNIQUE,
    name                VARCHAR(255)             NOT NULL UNIQUE, -- trading name shown to travelers
    code                VARCHAR(255)             NOT NULL UNIQUE,
    legal_name          VARCHAR(255),                             -- registered company name
    registration_number VARCHAR(100) UNIQUE,                      -- business registration number
    license_number      VARCHAR(100) UNIQUE,                      -- tourism (e.g. TALA) licence number
    email               VARCHAR(255)             NOT NULL,
    phone               VARCHAR(30)              NOT NULL,
    website             VARCHAR(255),
    address             TEXT,
    geography_id        BIGINT,                                   -- where the operator is based
    description         TEXT,
    is_verified         BOOLEAN                  NOT NULL DEFAULT FALSE,
    is_active           BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at          TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_tour_operators_geography
        FOREIGN KEY (geography_id)
            REFERENCES geographies (id)
            ON DELETE SET NULL
            ON UPDATE CASCADE
);

CREATE INDEX idx_tour_operators_geography_id ON tour_operators (geography_id);

