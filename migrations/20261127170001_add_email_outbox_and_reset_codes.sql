-- Transactional outbox: every email is written here in the same database
-- transaction as the change that causes it, then a relay publishes it to
-- RabbitMQ and the worker sends it. status: pending (not yet published),
-- queued (on RabbitMQ), sent, failed (gave up after the last retry).
CREATE TABLE email_outbox (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid          UUID         NOT NULL UNIQUE,
    kind          VARCHAR(60)  NOT NULL,
    to_address    VARCHAR(255) NOT NULL,
    content       JSONB        NOT NULL,
    status        VARCHAR(10)  NOT NULL DEFAULT 'pending'
                  CHECK (status IN ('pending', 'queued', 'sent', 'failed')),
    attempts      INT          NOT NULL DEFAULT 0,
    last_error    TEXT,
    published_at  TIMESTAMPTZ,
    sent_at       TIMESTAMPTZ,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_email_outbox_pending ON email_outbox (created_at) WHERE status = 'pending';

-- Password reset by one-time code (replaces emailed reset links). Only an
-- HMAC of the 6-digit code is stored; wrong guesses are counted.
DROP TABLE IF EXISTS password_reset_tokens;
CREATE TABLE password_reset_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    code_hash   CHAR(64)    NOT NULL,
    attempts    INT         NOT NULL DEFAULT 0,
    expires_at  TIMESTAMPTZ NOT NULL,
    used_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_password_reset_codes_user ON password_reset_codes (user_id, created_at DESC);

