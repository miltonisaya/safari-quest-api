-- The day-by-day plan of a sale package.
CREATE TABLE package_itinerary_days
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid          UUID                     NOT NULL UNIQUE,
    package_id    BIGINT                   NOT NULL REFERENCES packages (id) ON DELETE CASCADE,
    day_number    INTEGER                  NOT NULL,
    title         VARCHAR(255)             NOT NULL,
    description   TEXT                     NOT NULL,
    accommodation VARCHAR(255),
    meals         JSONB                    NOT NULL DEFAULT '[]'::jsonb, -- e.g. ["breakfast","dinner"]
    attraction_id BIGINT REFERENCES attractions (id) ON DELETE SET NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT uq_package_itinerary_day UNIQUE (package_id, day_number),
    CONSTRAINT chk_package_itinerary_day CHECK (day_number >= 1)
);

CREATE INDEX idx_package_itinerary_days_attraction_id ON package_itinerary_days (attraction_id);

