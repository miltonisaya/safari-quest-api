CREATE TABLE attractions
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                   UUID                     NOT NULL UNIQUE,
    name                   VARCHAR(255)             NOT NULL UNIQUE,
    code                   VARCHAR(255)             NOT NULL UNIQUE,
    description            TEXT,
    attraction_type_id     BIGINT                   NOT NULL,
    attraction_category_id BIGINT                   NOT NULL,
    geography_id           BIGINT                   NOT NULL,
    latitude               NUMERIC(9, 6),
    longitude              NUMERIC(9, 6),
    is_active              BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at             TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_attractions_attraction_type
        FOREIGN KEY (attraction_type_id) REFERENCES attraction_types (id)
            ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_attractions_attraction_category
        FOREIGN KEY (attraction_category_id) REFERENCES attraction_categories (id)
            ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_attractions_geography
        FOREIGN KEY (geography_id) REFERENCES geographies (id)
            ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_attractions_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_attractions_longitude CHECK (longitude BETWEEN -180 AND 180)
);

CREATE INDEX idx_attractions_attraction_type_id ON attractions (attraction_type_id);
CREATE INDEX idx_attractions_attraction_category_id ON attractions (attraction_category_id);
CREATE INDEX idx_attractions_geography_id ON attractions (geography_id);

