-- Everyone travelling on a booking: one lead (the booker, with ID) and the
-- members. The age group is copied as text so later changes to the groups
-- never rewrite history; the link is kept to stop deleting groups in use.
CREATE TABLE booking_travellers (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid               UUID         NOT NULL UNIQUE,
    booking_id         BIGINT       NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    is_lead            BOOLEAN      NOT NULL DEFAULT FALSE,
    position           INT          NOT NULL,
    full_name          VARCHAR(200) NOT NULL,
    email              VARCHAR(255),
    phone              VARCHAR(30),
    nationality        CHAR(2)      NOT NULL,
    age_group_id       BIGINT       REFERENCES age_groups(id) ON DELETE SET NULL,
    age_group_name     VARCHAR(60)  NOT NULL,
    age_min            INT          NOT NULL,
    age_max            INT,
    id_type            VARCHAR(20)  CHECK (id_type IS NULL OR id_type IN ('passport', 'national_id')),
    id_number          VARCHAR(50),
    id_expiry          DATE,
    -- Copy of the lead's ID, stored outside the public uploads folder and
    -- deleted automatically after the trip (System Settings).
    id_document_path   TEXT,
    id_document_name   VARCHAR(255),
    id_document_type   VARCHAR(100),
    id_uploaded_at     TIMESTAMPTZ,
    id_deleted_at      TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    UNIQUE (booking_id, position)
);
CREATE UNIQUE INDEX idx_booking_travellers_one_lead ON booking_travellers (booking_id) WHERE is_lead;
CREATE INDEX idx_booking_travellers_id_document ON booking_travellers (booking_id) WHERE id_document_path IS NOT NULL;

