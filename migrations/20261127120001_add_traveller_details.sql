-- Administrator-configurable age groups. They must start at 0 and run without
-- gaps or overlaps; the oldest has no upper age (max_age NULL).
CREATE TABLE age_groups (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid        UUID        NOT NULL UNIQUE,
    name        VARCHAR(60) NOT NULL,
    min_age     INT         NOT NULL CHECK (min_age >= 0),
    max_age     INT         CHECK (max_age IS NULL OR max_age >= min_age),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

